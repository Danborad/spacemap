    function mountIcons() {
        document.querySelectorAll('[data-icon]').forEach(el => {
            const name = el.getAttribute('data-icon');
            if (ICONS[name]) el.innerHTML = ICONS[name];
        });
    }

    function escapeHtml(value) {
        return String(value ?? '').replace(/[&<>"']/g, ch => ({
            '&': '&amp;',
            '<': '&lt;',
            '>': '&gt;',
            '"': '&quot;',
            "'": '&#39;'
        }[ch]));
    }

    function formatBytes(bytes) {
        const n = Number(bytes) || 0;
        if (n <= 0) return '0 B';
        const units = ['B', 'KB', 'MB', 'GB', 'TB', 'PB'];
        const i = Math.min(Math.floor(Math.log(n) / Math.log(1024)), units.length - 1);
        return (n / Math.pow(1024, i)).toFixed(i === 0 ? 0 : 2) + ' ' + units[i];
    }

    function formatTimeSec(sec) {
        if (!sec) return '-';
        return new Date(sec * 1000).toLocaleString('zh-CN', {
            year: 'numeric', month: '2-digit', day: '2-digit',
            hour: '2-digit', minute: '2-digit'
        });
    }

    function formatTimeMs(ms) {
        if (!ms) return '-';
        return new Date(ms).toLocaleString('zh-CN', {
            year: 'numeric', month: '2-digit', day: '2-digit',
            hour: '2-digit', minute: '2-digit', second: '2-digit'
        });
    }

    function formatDuration(ms) {
        const sec = Math.max(0, Math.floor((ms || 0) / 1000));
        if (sec < 60) return `${sec} 秒`;
        const m = Math.floor(sec / 60);
        const s = sec % 60;
        return `${m} 分 ${s} 秒`;
    }

    function typeLabel(t) {
        return TYPE_LABELS[t] || '其他';
    }

    function typeColor(t) {
        return TYPE_COLORS[t] || '#94a3b8';
    }

    function toast(msg, kind = 'info') {
        const box = document.getElementById('toastContainer');
        if (!box) return;
        const el = document.createElement('div');
        el.className = `toast ${kind}`;
        el.textContent = msg;
        box.appendChild(el);
        setTimeout(() => {
            el.style.opacity = '0';
            el.style.transition = 'opacity 0.2s ease';
            setTimeout(() => el.remove(), 220);
        }, 3200);
    }

    function confirmDialog({ title, desc, items = [], okText = '确认永久删除' }) {
        return new Promise(resolve => {
            const modal = document.getElementById('confirmModal');
            const titleEl = document.getElementById('confirmModalTitle');
            const descEl = document.getElementById('confirmModalDesc');
            const listEl = document.getElementById('confirmModalList');
            const okBtn = document.getElementById('confirmOkBtn');
            const cancelBtn = document.getElementById('confirmCancelBtn');

            titleEl.textContent = title || '确认操作';
            descEl.textContent = desc || '';
            okBtn.textContent = okText;

            if (items.length > 0) {
                listEl.classList.remove('hidden');
                const preview = items.slice(0, 50);
                listEl.innerHTML = preview.map(p => `<li>${escapeHtml(p)}</li>`).join('') +
                    (items.length > 50 ? `<li>... 还有 ${items.length - 50} 个文件</li>` : '');
            } else {
                listEl.classList.add('hidden');
                listEl.innerHTML = '';
            }

            const cleanup = (result) => {
                modal.classList.add('hidden');
                okBtn.onclick = null;
                cancelBtn.onclick = null;
                resolve(result);
            };

            okBtn.onclick = () => cleanup(true);
            cancelBtn.onclick = () => cleanup(false);
            modal.classList.remove('hidden');
        });
    }

    async function copyText(text) {
        if (!text) return false;
        try {
            if (navigator.clipboard && window.isSecureContext) {
                await navigator.clipboard.writeText(text);
                return true;
            }
        } catch (_) {}
        try {
            const ta = document.createElement('textarea');
            ta.value = text;
            ta.setAttribute('readonly', '');
            ta.style.position = 'fixed';
            ta.style.left = '-9999px';
            ta.style.top = '-9999px';
            document.body.appendChild(ta);
            ta.focus();
            ta.select();
            const ok = document.execCommand('copy');
            document.body.removeChild(ta);
            return !!ok;
        } catch (_) {
            return false;
        }
    }

